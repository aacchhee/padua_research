# -------------------------------------------------------------- simulated 'computed' run (T-104, T-106)
def simulated_run(xs, ys, nmax, noise=Fr(1, 10 ** 6)):
    """Window recurrence (dev choice, exact window) in rationals with injected local errors:
    coefficients h = exact projections onto the computed window, rounded to a grid; beta = rounded value;
    then q_k := (A q_p - Q_W h - f_k)/beta with random rational f_k. The local relation holds exactly."""
    idx = cols(nmax); pos = {k: i for i, k in enumerate(idx)}
    M = len(xs)
    Q = [[Fr(1, 1)] * M]
    # crude normalisation of q0 by a rational close to 1/sqrt(M)
    s0 = Fr(round(10 ** 6 / (M ** 0.5)), 10 ** 6)
    Q[0] = [s0] * M
    recs = [None]
    rnd = lambda v: Fr(round(float(v) * 10 ** 8), 10 ** 8)
    for k in range(1, len(idx)):
        t, j = idx[k]
        op, par = ('X', (t - 1, 0)) if j == 0 else ('Y', (t - 1, j - 1))
        p = pos[par]
        a = [(x if op == 'X' else y) * v for x, y, v in zip(xs, ys, Q[p])]
        W = []
        if t >= 2:
            i0 = j if op == 'X' else max(j - 2, 0)
            W += [pos[(t - 2, i)] for i in range(i0, t - 1)]
        W += [pos[(t - 1, i)] for i in range(t)] + [pos[(t, i)] for i in range(j)]
        h = [rnd(dot(a, Q[l])) for l in W]
        r = list(a)
        for hl, l in zip(h, W):
            r = [ri - hl * ql for ri, ql in zip(r, Q[l])]
        beta = rnd(sum(v * v for v in r) ** 0.5 if False else float(sum(v * v for v in r)) ** 0.5)
        f = [noise * rat() for _ in range(M)]
        qk = [(ri - fi) / beta for ri, fi in zip(r, f)]
        Q.append(qk)
        recs.append((op, p, W, h, beta, f))
    return idx, pos, Q, recs



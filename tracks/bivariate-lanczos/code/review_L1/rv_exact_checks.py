def rat(lo=-1, hi=1, den=97):
    return Fr(random.randint(lo * den, hi * den), den)


def dot(u, v, w=None):
    if w is None:
        return sum(a * b for a, b in zip(u, v))
    return sum(a * b * c for a, b, c in zip(u, v, w))


def cols(n):
    return [(t, j) for t in range(n + 1) for j in range(t + 1)]


# -------------------------------------------------------------- T-101 supports (unnormalised, weighted GS)
def gs_graded(xs, ys, ws, nmax, choice='dev'):
    """Exact weighted Gram-Schmidt (orthogonal, not normalised) in graded order, generated by the
    window-free full orthogonalisation; returns dict (t,j) -> node vector. Uses parent rule for the product."""
    idx = cols(nmax)
    V = {(0, 0): [Fr(1)] * len(xs)}
    for (t, j) in idx[1:]:
        if choice == 'dev':
            op, par = ('X', (t - 1, 0)) if j == 0 else ('Y', (t - 1, j - 1))
        else:
            op, par = ('Y', (t - 1, t - 1)) if j == t else ('X', (t - 1, j))
        a = [(x if op == 'X' else y) * v for x, y, v in zip(xs, ys, V[par])]
        r = list(a)
        for l in idx[:idx.index((t, j))]:
            c = dot(a, V[l], ws) / dot(V[l], V[l], ws)
            r = [ri - c * vi for ri, vi in zip(r, V[l])]
        if all(ri == 0 for ri in r):
            raise ZeroDivisionError('breakdown at %s' % ((t, j),))
        V[(t, j)] = r
    return V


def support_check(xs, ys, ws, n, label):
    V = gs_graded(xs, ys, ws, n + 1)
    idx = cols(n + 1)
    bad = 0; count = 0
    for (t, j) in cols(n):
        for op in ('X', 'Y'):
            Av = [(x if op == 'X' else y) * v for x, y, v in zip(xs, ys, V[(t, j)])]
            for (s, i) in idx:
                val = dot(Av, V[(s, i)], ws)
                if op == 'Y':
                    allowed = (s == t - 1 and i >= j - 1) or s == t or (s == t + 1 and i <= j + 1)
                else:
                    allowed = (s == t - 1 and i >= j) or s == t or (s == t + 1 and i <= j)
                allowed = allowed or (s == t - 1 and False)
                if not allowed:
                    count += 1
                    if val != 0:
                        bad += 1
    print(f"T-101 supports [{label}] n={n}: entries outside derived support = {count}, nonzero among them = {bad}")


def implicit_column_check(xs, ys, ws, n):
    """T-101 part 5 with normalised-free form: for orthogonal (unnormalised) V, define the J-section in the
    orthonormal basis; check the recursion beta H_J e_(t,j) = H_F H_J e_(t-1,j-1) - sum h_l H_J e_l exactly
    using normalised quantities squared-free: we verify the equivalent vector identity
      beta J q_(t,j) = F J q_(t-1,j-1) - sum h_l J q_l  (which, projected, is part 5)."""
    V = gs_graded(xs, ys, ws, n + 1)
    idx = cols(n)
    err = 0
    for (t, j) in idx:
        if t == 0 or j == 0:
            continue
        par = (t - 1, j - 1)
        a = [y * v for y, v in zip(ys, V[par])]
        # coefficients of the F-product in the orthogonal basis: a = sum_l c_l V_l + V_(t,j)
        prev = idx[:idx.index((t, j))]
        c = {l: dot(a, V[l], ws) / dot(V[l], V[l], ws) for l in prev}
        lhs = [x * v for x, v in zip(xs, V[(t, j)])]
        Jpar = [x * v for x, v in zip(xs, V[par])]
        rhs = [y * v for y, v in zip(ys, Jpar)]
        for l, cl in c.items():
            rhs = [ri - cl * x * vl for ri, x, vl in zip(rhs, xs, V[l])]
        err += sum(1 for p, q in zip(lhs, rhs) if p != q)
        # supports of c: only exact window of (t,j) may be nonzero
        for (s, i), cl in c.items():
            inwin = (s == t - 2 and i >= j - 2) or s == t - 1 or (s == t and i < j)
            if cl != 0 and not inwin:
                err += 1
    print(f"T-101 part 5 (implicit J-column identity) and exact window of F-products: mismatches = {err}")


# -------------------------------------------------------------- T-103 Paige identity (exact, random data)
def T103_check(trials=5, m=9, q=4, r=3, Mv=14, b=2, break_band=False):
    worst = 0
    for _ in range(trials):
        A = [rat() for _ in range(Mv)]
        Qh = sp.Matrix(Mv, m, lambda i, k: rat())
        Qp = sp.Matrix(Mv, q, lambda i, k: rat())
        T = sp.zeros(m, m)
        for k in range(m):
            for l in range(m):
                if abs(k - l) <= b:
                    T[k, l] = rat()
        if break_band:
            T[0, m - 1] = rat() + 1
        B = sp.zeros(q, m)
        for k in range(q):
            for l in range(m - r, m):
                B[k, l] = rat()
        E = sp.diag(*A) * Qh - Qh * T - Qp * B
        C = Qh.T * Qh; c = Qh.T * Qp
        S = (T + T.T) / 2; K = (T - T.T) / 2; G = C - sp.eye(m)
        Dl = sp.diag(*[C[i, i] - 1 for i in range(m)])
        R = sp.Matrix(m, m, lambda i, k: C[i, k] if k > i else 0)
        Rloc = sp.Matrix(m, m, lambda i, k: R[i, k] if 0 < k - i <= b else 0)
        up = lambda Mx: sp.Matrix(m, m, lambda i, k: Mx[i, k] if k > i else 0)
        low = lambda Mx: sp.Matrix(m, m, lambda i, k: Mx[i, k] if k < i else 0)
        dg = lambda Mx: sp.diag(*[Mx[i, i] for i in range(m)])
        lowd = lambda Mx: sp.Matrix(m, m, lambda i, k: Mx[i, k] if k <= i else 0)
        Phi = E.T * Qh - Qh.T * E - 2 * K - G * K - K * G
        Xl = Rloc * S - S * Rloc
        Om = low(Xl) + low(Xl).T + dg(Xl) - up(Dl * S - S * Dl) + up(B.T * c.T) + lowd(c * B) + up(Phi)
        s = sp.Matrix(m, 1, lambda i, k: rat()); th = rat()
        rho = S * s - th * s
        lhs = (s.T * c * B * s)[0]
        rhs = (s.T * Om * s)[0] - (s.T * (R - R.T) * rho)[0]
        worst = max(worst, abs(lhs - rhs))
    tag = ' (bandwidth hypothesis deliberately violated)' if break_band else ''
    print(f"T-103 identity, {trials} random rational instances{tag}: max |lhs - rhs| = {worst}")



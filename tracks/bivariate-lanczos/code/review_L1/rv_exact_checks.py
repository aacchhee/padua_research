def T105_impulse_check():
    """numerical (mpmath, 50 digits) check of rho^[s]_j = b_s (r_{s-1} sigma_j - sigma_{s-1} r_j)"""
    import mpmath as mp
    mp.mp.dps = 50
    pts = [mp.mpf(-1), mp.mpf('-0.4'), mp.mpf('0.1'), mp.mpf('0.55'), mp.mpf('0.8'), mp.mpf(1)]
    wts = [mp.mpf(k) for k in (1, 2, 3, 1, 2, 1)]; tot = sum(wts); wts = [w_ / tot for w_ in wts]
    # Stieltjes in mp
    nm = 5
    p_prev = [mp.mpf(0)] * 6; p = [mp.mpf(1)] * 6
    a_, b_ = [], [mp.mpf(0)]
    P = [p]
    for l in range(nm):
        al = sum(w_ * t * q * q for w_, t, q in zip(wts, pts, p))
        rr = [(t - al) * q - b_[-1] * qp for t, q, qp in zip(pts, p, p_prev)]
        bl = mp.sqrt(sum(w_ * r_ * r_ for w_, r_ in zip(wts, rr)))
        a_.append(al); b_.append(bl)
        p_prev, p = p, [r_ / bl for r_ in rr]
        P.append(p)
    def rvals(eta):
        r = [mp.mpf(1), (eta - a_[0]) / b_[1]]
        for l in range(1, nm - 1):
            r.append(((eta - a_[l]) * r[l] - b_[l] * r[l - 1]) / b_[l + 1])
        return r
    def sig(eta):
        out = [mp.mpf(0)]
        for l in range(1, nm):
            s = mp.mpf(0)
            for t, w_ in zip(pts, wts):
                rl_eta = rvals(eta)[l]; rl_t = rvals(t)[l]
                s += w_ * (rl_eta - rl_t) / (eta - t) if eta != t else 0
            out.append(s)
        return out
    eta = mp.mpf('0.3')
    r = rvals(eta); sg = sig(eta)
    worst = mp.mpf(0)
    for s in range(1, nm - 1):
        rho = [mp.mpf(0)] * nm; rho[s] = mp.mpf(1)
        for l in range(s, nm - 1):
            rho[l + 1] = ((eta - a_[l]) * rho[l] - b_[l] * rho[l - 1]) / b_[l + 1]
        for jj in range(s, nm):
            formula = b_[s] * (r[s - 1] * sg[jj] - sg[s - 1] * r[jj])
            worst = max(worst, abs(formula - rho[jj]))
    print(f"T-105 impulse-response formula (mpmath 50 digits, 6-point measure, eta=0.3): max error = {mp.nstr(worst, 5)}")


# -------------------------------------------------------------- T-401 lemmas, hypothesis necessity
def span_rank(vecs):
    """exact rank by fraction Gaussian elimination"""
    rows = [list(v) for v in vecs]
    if not rows:
        return 0
    rank = 0; ncol = len(rows[0])
    for c in range(ncol):
        piv = next((i for i in range(rank, len(rows)) if rows[i][c] != 0), None)
        if piv is None:
            continue
        rows[rank], rows[piv] = rows[piv], rows[rank]
        pr = rows[rank]
        for i in range(rank + 1, len(rows)):
            if rows[i][c] != 0:
                f = rows[i][c] / pr[c]
                rows[i] = [a - f * b for a, b in zip(rows[i], pr)]
        rank += 1
    return rank


def poly_vecs(xs, ys, deg, wvec=None):
    out = []
    for t in range(deg + 1):
        for j in range(t + 1):
            out.append([x ** (t - j) * y ** j for x, y in zip(xs, ys)])
    return out



"""R06: which coefficient errors carry the clustered-checkerboard loss (IDEA?bivariate-lanczos-claude-117)?
Xi(c) = node values of the polynomials generated by window coefficients c (BJ ordering, block window) from q0,
built in long double without forcing; D(n) = max |Xi_n^T Xi_n - I|.  Coefficient sets: exact product-type c*
(univariate Jacobi coefficients of the factors, long double), the BJ run's computed coefficients c_BJ, and
mixtures / u-sized perturbations.  MEASURED only.  Usage: python3 -I l1_r06_coefficient_channel.py"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import l1_recurrence as L
import l1_r04_checkerboard as C
# l1_r04_checkerboard_diag.py (frozen) runs its diagnosis at import; the bodies of its two helpers are copied verbatim below (docstrings added).

LD = np.longdouble
EPS = 2.0 ** -52
Nof = lambda n: (n + 1) * (n + 2) // 2


def jacobi_1d_ld(t, w, n):
    """copy of l1_r04_checkerboard_diag.jacobi_1d_ld (long-double Lanczos, 3 reorthogonalisation passes)"""
    t = t.astype(LD); M = len(t); Q = np.zeros((M, n + 2), dtype=LD); v = np.sqrt(w.astype(LD))
    Q[:, 0] = v / np.sqrt(np.sum(v * v)); a = np.zeros(n + 1, dtype=LD); b = np.zeros(n + 2, dtype=LD)
    for k in range(n + 1):
        u = t * Q[:, k]; a[k] = Q[:, k] @ u
        for _ in range(3):
            u = u - Q[:, :k + 1] @ (Q[:, :k + 1].T @ u)
        b[k + 1] = np.sqrt(np.sum(u * u)); Q[:, k + 1] = u / b[k + 1]
    return a, b


def ref_coefs(ax, bx, ay, by, tab):
    """copy of l1_r04_checkerboard_diag.ref_coefs (product-pattern window coefficients, block window)"""
    idx, pos, parent, op, start = tab
    N = len(idx); coef = [None] * N
    for k in range(1, N):
        t, j = idx[k]; W = L.window(k, idx, start, 'block'); h = np.zeros(len(W), dtype=LD)
        for ii, l in enumerate(W):
            if j == 0:
                if idx[l] == (t - 1, 0): h[ii] = ax[t - 1]
                if idx[l] == (t - 2, 0): h[ii] = bx[t - 1]
            else:
                if idx[l] == (t - 1, j - 1): h[ii] = ay[j - 1]
                if idx[l] == (t - 2, j - 2): h[ii] = by[j - 1]
        coef[k] = (W, h, bx[t] if j == 0 else by[j])
    return coef


def pattern_mask(tab, N):
    idx, pos, parent, op, start = tab
    masks = [None] * N
    for k in range(1, N):
        t, j = idx[k]; W = L.window(k, idx, start, 'block')
        if j == 0:
            masks[k] = np.array([idx[l] in ((t - 1, 0), (t - 2, 0)) for l in W])
        else:
            masks[k] = np.array([idx[l] in ((t - 1, j - 1), (t - 2, j - 2)) for l in W])
    return masks


def xi_from(coef, x, y, w, tab, N):
    idx, pos, parent, op, start = tab
    xl, yl = x.astype(LD), y.astype(LD)
    Xi = np.zeros((len(x), N), dtype=LD); v = np.sqrt(w.astype(LD)); Xi[:, 0] = v / np.sqrt(np.sum(v * v))
    for k in range(1, N):
        W, h, beta = coef[k]; p = parent[k]; a = xl if op[k] == 'J' else yl
        Xi[:, k] = (a * Xi[:, p] - Xi[:, W] @ np.asarray(h, dtype=LD)) / LD(beta)
    G = Xi.T @ Xi
    return {n: float(np.abs(G[:Nof(n), :Nof(n)] - np.eye(Nof(n), dtype=LD)).max()) for n in (8, 12, 16, 20, 24)}


def mix(cA, cB, masks, N, use_on_from, use_off_from):
    """coefficient set taking pattern entries (and beta) from use_on_from, off-pattern entries from use_off_from"""
    out = [None] * N
    for k in range(1, N):
        W = cA[k][0]; mk = masks[k]
        on = np.asarray(use_on_from[k][1], dtype=LD); off = np.asarray(use_off_from[k][1], dtype=LD)
        out[k] = (W, np.where(mk, on, off), use_on_from[k][2])
    return out


def run(name, X, Y, nmax=24, seeds=(0, 1, 2)):
    P, w, wx, wy = C.checkerboard(X, Y); x, y = P[:, 0].copy(), P[:, 1].copy()
    Q, cbj, tab = L.recurrence(x, y, w, nmax, win='block', orth='cgs')
    N = Q.shape[1]; G = Q.T @ Q
    loss = {n: float(np.abs(G[:Nof(n), :Nof(n)] - np.eye(Nof(n))).max()) for n in (8, 12, 16, 20, 24)}
    ax, bx = jacobi_1d_ld(X, wx, nmax); ay, by = jacobi_1d_ld(Y, wy, nmax)
    cst = ref_coefs(ax, bx, ay, by, tab)
    masks = pattern_mask(tab, N)
    zero = [None] + [(cst[k][0], np.zeros(len(cst[k][0]), dtype=LD), cst[k][2]) for k in range(1, N)]
    rows = [('BJ loss L(n) (double run)', loss),
            ('D: exact c*', xi_from(cst, x, y, w, tab, N)),
            ('D: c_BJ', xi_from(cbj, x, y, w, tab, N)),
            ('D: c_BJ on-pattern, off zeroed', xi_from(mix(cst, cbj, masks, N, cbj, zero), x, y, w, tab, N)),
            ('D: c* + c_BJ off-pattern', xi_from(mix(cst, cbj, masks, N, cst, cbj), x, y, w, tab, N))]
    for lab, kind in [('D: c* + abs u-noise off-pattern (median)', 'abs_off'),
                      ('D: c* + rel u-noise on pattern+beta (median)', 'rel_on')]:
        res = []
        for sd in seeds:
            rng = np.random.default_rng(sd); cp = [None] * N
            for k in range(1, N):
                W, h, beta = cst[k]; h = np.array(h, dtype=LD); mk = masks[k]
                if kind == 'abs_off':
                    h = h + np.where(mk, 0.0, rng.standard_normal(len(h)) * EPS).astype(LD); b = beta
                else:
                    h = h * (1 + np.where(mk, rng.standard_normal(len(h)) * EPS, 0.0).astype(LD))
                    b = beta * (1 + LD(rng.standard_normal() * EPS))
                cp[k] = (W, h, b)
            res.append(xi_from(cp, x, y, w, tab, N))
        rows.append((lab, {n: float(np.median([r[n] for r in res])) for n in res[0]}))
    offmax = max(float(np.abs(np.where(masks[k], 0.0, np.asarray(cbj[k][1], dtype=float))).max()) if len(masks[k]) else 0.0
                 for k in range(1, N))
    onmax = max(float(np.abs(np.where(masks[k], np.asarray(cbj[k][1], dtype=LD) - cst[k][1], 0.0)).max()) if len(masks[k]) else 0.0
                for k in range(1, N))
    print(f"== checkerboard {name} (m={len(X) - 1}, M={len(x)}): max |c_BJ off-pattern| = {offmax:.1e}, "
          f"max |c_BJ - c*| on pattern = {onmax:.1e}", flush=True)
    for lab, d in rows:
        print(f"   {lab:46s} " + " ".join(f"n{n}:{v:.0e}" for n, v in d.items()), flush=True)


if __name__ == '__main__':
    print(f"# l1_r06_coefficient_channel.py numpy={np.__version__}")
    m = 30
    s1, s2 = np.linspace(-1, 1, m + 1), np.linspace(-1, 1, m + 2)
    run('cubic-clustered (s|s|^2, as R04/R05)', s1 * np.abs(s1) ** 2, s2 * np.abs(s2) ** 2)
    run('equispaced', s1, s2)

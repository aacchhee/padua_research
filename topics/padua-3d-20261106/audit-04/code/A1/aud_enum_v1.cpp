// Auditor's independent HNF lattice enumerator (Claude audit04, A1 scope).
// Written from the mathematical definitions; shares no code with the
// producer's r08_lattice_enum.cpp or Codex's r08_lattice_check.py.
//
// Lattice L = row span of B = [[a,b,c],[0,d,e],[0,0,f]], a,d,f>0,
// 0<=b<d, 0<=c<f, 0<=e<f (unique row-HNF; d*f^2 forms per diagonal).
// Admissible: no nonzero k in L with |k|_1 <= 2n-1.
// Membership test (exact divisibility): k in L  <=>  a | k1, u=k1/a,
//   d | (k2 - b u), v=(k2-bu)/d, f | (k3 - c u - e v).
// Short vectors are listed explicitly by brute force over the l1 ball,
// one of each pair +-k (first nonzero coordinate positive).
// For fixed (a,d,f,b,e) the c-dependence is handled by residue tables:
//   c forbidden <=> exists listed (u>0,v,k3) with c*u = k3 - e v (mod f),
//   or a listed u=0 vector already lies in L (then every c is forbidden).
// Fold: H = {x in (Z/q)^3 : B x = 0 mod q} generated by columns of
// q*B^{-1}; folded key = coordinatewise min(x, q-x); count with early stop.
//
// usage: aud_enum MODE n qlo qhi cap out.jsonl
//   MODE=min   : stop at first q with an admissible lattice; list all of them
//                with exact fold.
//   MODE=fold  : record every admissible lattice with fold <= cap (exact),
//                and the per-q counts.
//   MODE=selftest qmax : brute-force check of dual parametrization (q<=qmax).
#include <cstdio>
#include <cstdlib>
#include <cstdint>
#include <cstring>
#include <vector>
#include <string>
#include <algorithm>
#include <chrono>
#include <array>
using namespace std;

static inline long long pmod(long long x, long long m){ long long r=x%m; return r<0?r+m:r; }

struct SV { int k1,k2,k3; };

// open addressing set with generation stamps
struct FoldSet {
    vector<uint64_t> key; vector<uint32_t> gen; uint32_t g=1; size_t mask=0;
    void init(size_t cap){ size_t s=16; while(s<4*(cap+2)) s<<=1; key.assign(s,0); gen.assign(s,0); mask=s-1; g=1; }
    void reset(){ ++g; if(g==0){ fill(gen.begin(),gen.end(),0); g=1; } }
    // returns true if newly inserted
    bool insert(uint64_t k){ size_t h=(k*0x9E3779B97F4A7C15ULL)>>20; h&=mask;
        while(gen[h]==g){ if(key[h]==k) return false; h=(h+1)&mask; }
        gen[h]=g; key[h]=k; return true; }
};

// exact fold count if <= lim, otherwise lim+1
static int fold_count(int a,int b,int c,int d,int e,int f,int lim,FoldSet &S){
    long long q=1LL*a*d*f;
    // generators: columns of adj = q B^{-1}
    long long g1x=1LL*d*f, g2x=pmod(-1LL*b*f,q), g2y=1LL*a*f, g3x=pmod(1LL*b*e-1LL*c*d,q), g3y=pmod(-1LL*a*e,q), g3z=1LL*a*d;
    S.reset(); int cnt=0;
    long long x3=0,y3=0,z3=0; // j3*g3
    for(int j3=0;j3<f;++j3){
        long long x2=x3,y2=y3; // + j2*g2
        for(int j2=0;j2<d;++j2){
            long long x1=x2; // + j1*g1
            for(int j1=0;j1<a;++j1){
                long long X=x1, Y=y2, Z=z3;
                long long fx=min(X,q-X), fy=min(Y,q-Y), fz=min(Z,q-Z);
                uint64_t key=((uint64_t)fx<<42)|((uint64_t)fy<<21)|(uint64_t)fz;
                if(S.insert(key)){ if(++cnt>lim) return lim+1; }
                x1+=g1x; if(x1>=q) x1-=q;
            }
            x2+=g2x; if(x2>=q) x2-=q; y2+=g2y; if(y2>=q) y2-=q;
        }
        x3+=g3x; if(x3>=q) x3-=q; y3+=g3y; if(y3>=q) y3-=q; z3+=g3z; if(z3>=q) z3-=q;
    }
    return cnt;
}

static int selftest(int qmax){
    // For every HNF with q<=qmax: brute-force H = {x: Bx=0 mod q} over (Z/q)^3,
    // compare with the generator parametrization (as a set), and compare fold.
    long long checked=0;
    FoldSet S; S.init(qmax*2);
    for(int q=1;q<=qmax;++q) for(int a=1;a<=q;++a) if(q%a==0) for(int d=1;d<=q/a;++d) if((q/a)%d==0){
        int f=q/(a*d);
        for(int b=0;b<d;++b) for(int c=0;c<f;++c) for(int e=0;e<f;++e){
            vector<char> inH((size_t)q*q*q,0); int brute=0;
            for(int x=0;x<q;++x) for(int y=0;y<q;++y) for(int z=0;z<q;++z){
                if(pmod(1LL*a*x+1LL*b*y+1LL*c*z,q)==0 && pmod(1LL*d*y+1LL*e*z,q)==0 && pmod(1LL*f*z,q)==0){ inH[((size_t)x*q+y)*q+z]=1; ++brute; }
            }
            if(brute!=q){ printf("selftest FAIL |H|=%d q=%d\n",brute,q); return 1; }
            // parametrization
            long long g1x=1LL*d*f, g2x=pmod(-1LL*b*f,q), g2y=1LL*a*f, g3x=pmod(1LL*b*e-1LL*c*d,q), g3y=pmod(-1LL*a*e,q), g3z=1LL*a*d;
            vector<char> seen((size_t)q*q*q,0); int distinct=0;
            for(int j3=0;j3<f;++j3) for(int j2=0;j2<d;++j2) for(int j1=0;j1<a;++j1){
                long long X=pmod(j1*g1x+j2*g2x+j3*g3x,q), Y=pmod(j2*g2y+j3*g3y,q), Z=pmod(j3*g3z,q);
                size_t id=((size_t)X*q+Y)*q+Z; if(!inH[id]){ printf("selftest FAIL notinH\n"); return 1; }
                if(!seen[id]){ seen[id]=1; ++distinct; }
            }
            if(distinct!=q){ printf("selftest FAIL distinct=%d q=%d\n",distinct,q); return 1; }
            // brute fold
            vector<char> fs((size_t)q*q*q,0); int bf=0;
            for(int x=0;x<q;++x) for(int y=0;y<q;++y) for(int z=0;z<q;++z) if(inH[((size_t)x*q+y)*q+z]){
                int fx=min(x,q-x)%q, fy=min(y,q-y)%q, fz=min(z,q-z)%q; size_t id=((size_t)fx*q+fy)*q+fz; if(!fs[id]){fs[id]=1;++bf;}
            }
            int fc=fold_count(a,b,c,d,e,f,q,S);
            if(fc!=bf){ printf("selftest FAIL fold %d vs %d\n",fc,bf); return 1; }
            ++checked;
        }
    }
    printf("selftest OK hnfs=%lld qmax=%d\n",checked,qmax); return 0;
}

int main(int argc,char**argv){
    if(argc>=3 && string(argv[1])=="selftest") return selftest(atoi(argv[2]));
    if(argc!=7){ fprintf(stderr,"usage: aud_enum MODE n qlo qhi cap out\n"); return 2; }
    string mode=argv[1]; int n=atoi(argv[2]), qlo=atoi(argv[3]), qhi=atoi(argv[4]), cap=atoi(argv[5]);
    FILE *out=fopen(argv[6],"w"); if(!out) return 3;
    const int r=2*n-1;
    // explicit half l1-ball, brute force over the cube
    vector<SV> ball;
    for(int x=-r;x<=r;++x) for(int y=-r;y<=r;++y) for(int z=-r;z<=r;++z){
        if(abs(x)+abs(y)+abs(z)>r) continue; if(x==0&&y==0&&z==0) continue;
        bool pos = x>0 || (x==0 && (y>0 || (y==0 && z>0)));
        if(pos) ball.push_back({x,y,z});
    }
    fprintf(out,"{\"type\":\"ball\",\"n\":%d,\"half_ball_size\":%zu}\n",n,ball.size());
    auto t0=chrono::steady_clock::now();
    FoldSet S; S.init(mode=="min"? (size_t)qhi : (size_t)cap+1);
    long long T_all=0,T_adm=0,T_small=0; int minfold=-1;
    vector<vector<uint8_t>> R(r+1);
    for(int q=qlo;q<=qhi;++q){
        long long qall=0,qadm=0,qsmall=0; vector<array<int,6>> goods;
        for(int a=1;a<=q;++a){ if(q%a) continue;
          // vectors with a | k1
          vector<SV> Sa; for(auto &s:ball) if(s.k1%a==0) Sa.push_back(s);
          for(int d=1;d<=q/a;++d){ if((q/a)%d) continue; int f=q/(a*d);
            qall+=1LL*d*f*f;
            for(int u=0;u<=r;++u) R[u].assign(f,0);
            for(int b=0;b<d;++b){
                vector<array<int,3>> Z, P; // (u,v,k3)
                for(auto &s:Sa){ int u=s.k1/a; long long t=s.k2-1LL*b*u; if(pmod(t,d)) continue; int v=(int)((t - pmod(t,d))/d); // exact
                    if(1LL*d*v!=t){ fprintf(stderr,"div err\n"); return 5; }
                    if(u==0) Z.push_back({0,v,s.k3}); else P.push_back({u,v,s.k3}); }
                int umax=0; for(auto &p:P) umax=max(umax,p[0]);
                vector<int> step(umax+1); for(int u=1;u<=umax;++u) step[u]=u%f;
                vector<char> used(umax+1,0); for(auto &p:P) used[p[0]]=1;
                vector<int> us; for(int u=1;u<=umax;++u) if(used[u]) us.push_back(u);
                for(int e=0;e<f;++e){
                    bool zhit=false; for(auto &z:Z){ if(pmod(z[2]-1LL*e*z[1],f)==0){ zhit=true; break; } }
                    if(zhit) continue;
                    for(auto &p:P) R[p[0]][pmod(p[2]-1LL*e*p[1],f)]=1;
                    vector<int> cu(umax+1,0);
                    for(int c=0;c<f;++c){
                        bool forb=false;
                        for(int u:us){ if(R[u][cu[u]]){ forb=true; break; } }
                        if(!forb){
                            ++qadm;
                            if(mode=="min") goods.push_back({a,b,c,d,e,f});
                            else {
                                int m=fold_count(a,b,c,d,e,f,cap,S);
                                if(m<=cap){ ++qsmall; if(minfold<0||m<minfold) minfold=m;
                                    fprintf(out,"{\"type\":\"small\",\"q\":%d,\"fold\":%d,\"hnf\":[%d,%d,%d,%d,%d,%d]}\n",q,m,a,b,c,d,e,f); }
                            }
                        }
                        for(int u:us){ cu[u]+=step[u]; if(cu[u]>=f) cu[u]-=f; }
                    }
                    for(auto &p:P) R[p[0]][pmod(p[2]-1LL*e*p[1],f)]=0;
                }
            }
          }
        }
        T_all+=qall; T_adm+=qadm; T_small+=qsmall;
        double sec=chrono::duration<double>(chrono::steady_clock::now()-t0).count();
        fprintf(out,"{\"type\":\"q\",\"q\":%d,\"hnf_total\":%lld,\"admissible\":%lld,\"small\":%lld,\"sec\":%.3f}\n",q,qall,qadm,qsmall,sec); fflush(out);
        if(mode=="min" && qadm>0){
            for(auto &h:goods){ int m=fold_count(h[0],h[1],h[2],h[3],h[4],h[5],q,S);
                fprintf(out,"{\"type\":\"minimizer\",\"q\":%d,\"fold\":%d,\"hnf\":[%d,%d,%d,%d,%d,%d]}\n",q,m,h[0],h[1],h[2],h[3],h[4],h[5]); }
            double s2=chrono::duration<double>(chrono::steady_clock::now()-t0).count();
            fprintf(out,"{\"type\":\"summary\",\"mode\":\"min\",\"n\":%d,\"qlo\":%d,\"min_det\":%d,\"minimizers\":%zu,\"hnf_total\":%lld,\"sec\":%.3f}\n",n,qlo,q,goods.size(),T_all,s2);
            fclose(out); return 0;
        }
    }
    double sec=chrono::duration<double>(chrono::steady_clock::now()-t0).count();
    fprintf(out,"{\"type\":\"summary\",\"mode\":\"%s\",\"n\":%d,\"qlo\":%d,\"qhi\":%d,\"cap\":%d,\"hnf_total\":%lld,\"admissible\":%lld,\"small\":%lld,\"min_fold_le_cap\":%d,\"sec\":%.3f}\n",mode.c_str(),n,qlo,qhi,cap,T_all,T_adm,T_small,minfold,sec);
    fclose(out); return 0;
}

def need(ok, msg):
    if not ok:
        raise SystemExit('FAIL: ' + msg)

def modes(n, d=3):
    return [a for a in it.product(range(n+1), repeat=d) if sum(a) <= n]

def is_prime_td(p):
    if p < 2: return False
    q = 2
    while q*q <= p:
        if p % q == 0: return False
        q += 1
    return True

def order_brute(w, p):
    x, k = w % p, 1
    while x != 1:
        x = x*w % p; k += 1
        if k > p: return None
    return k

def rank_mod(A, p):
    A = [[v % p for v in r] for r in A]
    r = 0; ncol = len(A[0])
    for j in range(ncol):
        piv = None
        for i in range(r, len(A)):
            if A[i][j]: piv = i; break
        if piv is None: continue
        A[r], A[piv] = A[piv], A[r]
        inv = pow(A[r][j], p-2, p)
        A[r] = [v*inv % p for v in A[r]]
        for i in range(len(A)):
            if i != r and A[i][j]:
                c = A[i][j]; A[i] = [(x - c*y) % p for x, y in zip(A[i], A[r])]
        r += 1
    return r

def det_mod(A, p):
    A = [[v % p for v in r] for r in A]; n = len(A); d = 1
    for j in range(n):
        piv = next((i for i in range(j, n) if A[i][j]), None)
        if piv is None: return 0
        if piv != j: A[j], A[piv] = A[piv], A[j]; d = -d
        d = d*A[j][j] % p; inv = pow(A[j][j], p-2, p)
        for i in range(j+1, n):
            if A[i][j]:
                c = A[i][j]*inv % p; A[i] = [(x - c*y) % p for x, y in zip(A[i], A[j])]
    return d % p

def closure(gens, den):
    """Subgroup of (Z/den)^3 generated by integer triples (numerators over den)."""
    S = {(0, 0, 0)}; frontier = [(0, 0, 0)]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = tuple((a+b) % den for a, b in zip(x, g))
                if y not in S: S.add(y); nxt.append(y)
        frontier = nxt
    return S


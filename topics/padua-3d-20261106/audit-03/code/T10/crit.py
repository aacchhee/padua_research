"""Auditor check of the scaled critical lattice L_m = m*L0, L0 rows [[1,0,7],[0,1,11],[0,0,38]]."""
import itertools as it, numpy as np, math, json, sys
def shortest_l1(B,R):
    best=None
    for c in it.product(range(-R,R+1),repeat=3):
        if c==(0,0,0): continue
        k=np.array(c)@B; s=int(np.abs(k).sum())
        if best is None or s<best: best=s
    return best
L0=np.array([[1,0,7],[0,1,11],[0,0,38]])
out={}
# shortest vector of L0 by brute force over coefficients (norm 6 => coefficients bounded)
out['L0_shortest']=shortest_l1(L0,8)
out['L0_det']=int(round(np.linalg.det(L0)))
out['density']=str((4/3)*27/38)
# dual group H0: h/38 with B h = 0 mod 38 -> generated by (-7,-11,1)
q=38;H0={tuple((t*np.array([-7,-11,1]))%q) for t in range(q)}
assert all(((L0@np.array(h))%q==0).all() for h in H0) and len(H0)==38
signs=list(it.product([1,-1],repeat=3))
U0={tuple((np.array(s)*np.array(h))%q) for s in signs for h in H0}
out['U0']=len(U0)
rows=[]
for m in range(1,7):
    Q=38*m
    # H_m = [m]^{-1}(H0): h/Q with m*h/Q in H0/38 -> h numerators mod Q with h = h0 + 38*j ... direct: B_m h = 0 mod Q
    Bm=m*L0
    Hm=[(h1,h2,h3) for h3 in range(Q) for h2 in [(-11*h3)%Q] for h1 in [(-7*h3)%Q]]
    # general solution: B_m h = 0 mod Q  <=> m*(h1+7h3)=0, m*(h2+11h3)=0, 38m h3 = 0 mod 38m
    Hm=[]
    for h3 in range(Q):
        for t1 in range(m):
            for t2 in range(m):
                h1=(-7*h3+t1*38)%Q; h2=(-11*h3+t2*38)%Q
                Hm.append((h1,h2,h3))
    Hm=set(Hm); assert len(Hm)==38*m**3
    assert all(((Bm@np.array(h))%Q==0).all() for h in list(Hm)[:2000])
    Um={tuple((np.array(s)*np.array(h))%Q) for s in signs for h in Hm}
    X={tuple(min(x,Q-x) for x in h) for h in Hm}
    N=math.comb(3*m+3,3)
    rows.append({'m':m,'det':38*m**3,'shortest':int(shortest_l1(Bm,8)) if m<=2 else 'scaled','Um':len(Um),'146m3':146*m**3,'X':len(X),'73m3/4':73*m**3/4,'N':N,'ratio':len(X)/N})
    print(rows[-1],flush=True)
out['rows']=rows
json.dump(out,open(sys.argv[1],'w'))
print(out['L0_shortest'],out['L0_det'],out['U0'],out['density'])
